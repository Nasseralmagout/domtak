// Generates src/components/iconPaths.ts: SVG path data for every Material Community icon
// referenced in src/. The web build draws icons as vector paths (crisp, and exportable to SVG/Figma);
// native keeps using the icon font. Run after adding new icon names: `npm run icons`.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as mdiModule from '@mdi/js';

const mdi = { ...mdiModule };
const glyphs = JSON.parse(readFileSync('node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json', 'utf8'));
const toKey = (name) => 'mdi' + name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

const used = new Set();
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f) && !p.endsWith('iconPaths.ts')) {
      for (const m of readFileSync(p, 'utf8').matchAll(/['"]([a-z0-9]+(?:-[a-z0-9]+)*)['"]/g)) {
        if (glyphs[m[1]] !== undefined && mdi[toKey(m[1])]) used.add(m[1]);
      }
    }
  }
};
walk('src');
const names = [...used].sort();
const body = names.map((n) => `  '${n}': '${mdi[toKey(n)]}',`).join('\n');
writeFileSync('src/components/iconPaths.ts', `// Generated by scripts/gen-icon-paths.mjs — do not edit by hand.\nexport const ICON_PATHS: Record<string, string> = {\n${body}\n};\n`);
console.log(`iconPaths.ts: ${names.length} icons`);
